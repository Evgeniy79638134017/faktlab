/* Диагностика готовности к продаже.
   Двенадцать утверждений, три ответа: да / нет / не знаю. «Не знаю» считается
   как «нет» — покупатель не примет ответ «надо посмотреть». На выходе процент
   и разбор по каждому незакрытому пункту: что это значит и за какой срок чинится. */
(function () {
  var root = document.getElementById('diag');
  if (!root) return;

  var Q = [
    { t: 'Прибыль или доход от объекта подтверждается документами за последние 12 месяцев',
      w: 3, why: 'Первое, что проверит покупатель. Слова и вилка «от и до» читаются как «никто не считал» и сразу становятся поводом для торга.',
      fix: 'Сводится за 3–5 дней, если есть первичка: выписки, отчёты, договоры.' },
    { t: 'Все правоустанавливающие документы на руках и свежие',
      w: 3, why: 'Выписка годовой давности не годится: покупатель закажет свою и найдёт то, о чём вы не знали.',
      fix: 'Заказ выписок — от трёх дней до двух недель, в зависимости от реестра.' },
    { t: 'Известно, есть ли обременения, аресты и права третьих лиц',
      w: 3, why: 'Неожиданное обременение обрушивает сделку на финальной стадии, когда уже потрачено время обеих сторон.',
      fix: 'Проверяется за несколько дней по открытым реестрам и выпискам.' },
    { t: 'Понятно, что именно передаётся покупателю: имущество, доля, права, база',
      w: 3, why: 'Собственник и покупатель часто понимают предмет сделки по-разному — и выясняется это у юриста, а не на встрече.',
      fix: 'Формулируется за день-два вместе с описью того, что входит.' },
    { t: 'Цена обоснована расчётом, а не ощущением или ценой соседнего объявления',
      w: 3, why: 'Цена без обоснования — приглашение к торгу. Покупатель начнёт снизу и будет прав, потому что аргументов против у вас нет.',
      fix: 'Две недели: расчёт двумя способами и сбор сопоставимых предложений.' },
    { t: 'Есть письменный документ, который можно отправить покупателю до встречи',
      w: 2, why: 'Пока материалов нет, каждый разговор начинается с нуля и держится на вашей памяти.',
      fix: 'Две–три недели на сбор и вёрстку пакета.' },
    { t: 'Известно, кто конкретно может купить этот объект и зачем',
      w: 2, why: 'Объявление «для всех» не работает: у профильного покупателя свои критерии, и обращаться к нему нужно на его языке.',
      fix: 'Неделя: сегменты, каталог адресатов, тексты обращений.' },
    { t: 'Подготовлены ответы на неудобные вопросы: почему продаёте, что не так',
      w: 2, why: 'Уклончивый ответ на «почему продаёте» читается как «дела плохи» и стоит дороже честного.',
      fix: 'Полдня разговора и формулировок.' },
    { t: 'Объект может работать без вашего ежедневного участия',
      w: 2, why: 'Если всё держится на собственнике, покупатель приобретает не актив, а работу — и платит соответственно.',
      fix: 'От месяца: регламенты, передача доступов и связей.' },
    { t: 'Известна стоимость владения: налоги, аренда, содержание, обслуживание',
      w: 2, why: 'Покупатель считает не цену покупки, а стоимость владения на несколько лет вперёд.',
      fix: 'Два-три дня сведения расходов.' },
    { t: 'Продажа идёт больше чем по одному каналу',
      w: 1, why: 'Одна площадка — это не выход на рынок, а надежда, что покупатель сам вас найдёт.',
      fix: 'Три дня на запуск нескольких каналов, если материалы готовы.' },
    { t: 'Известно, за сколько уходили похожие объекты в вашем регионе',
      w: 1, why: 'Без этого невозможно понять, ваша цена рыночная или вы стоите дороже рынка и потому не продаётесь.',
      fix: 'Неделя на сбор и проверку сопоставимых предложений.' }
  ];

  var answers = {};

  function el(tag, cls, html) {
    var n = document.createElement(tag);
    if (cls) n.className = cls;
    if (html != null) n.innerHTML = html;
    return n;
  }

  function render() {
    root.innerHTML = '';
    var list = el('div', 'dg__list');
    Q.forEach(function (q, i) {
      var row = el('div', 'dg__i' + (answers[i] ? ' is-' + answers[i] : ''));
      row.innerHTML =
        '<span class="dg__n">' + String(i + 1).padStart(2, '0') + '</span>' +
        '<span class="dg__t">' + q.t + '</span>' +
        '<span class="dg__a">' +
          btn(i, 'yes', 'да') + btn(i, 'no', 'нет') + btn(i, 'idk', 'не знаю') +
        '</span>';
      list.appendChild(row);
    });
    root.appendChild(list);
    root.appendChild(el('div', 'dg__out', ''));
    root.querySelectorAll('.dg__b').forEach(function (b) {
      b.addEventListener('click', function () {
        answers[+this.dataset.i] = this.dataset.v;
        render();
        var out = root.querySelector('.dg__out');
        if (out && Object.keys(answers).length === Q.length) {
          out.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
        }
      });
    });
    result();
  }

  function btn(i, v, t) {
    return '<button type="button" class="dg__b' + (answers[i] === v ? ' is-on' : '') +
           '" data-i="' + i + '" data-v="' + v + '">' + t + '</button>';
  }

  function result() {
    var out = root.querySelector('.dg__out');
    var done = Object.keys(answers).length;
    if (done < Q.length) {
      out.innerHTML = '<p class="dg__hint">Отвечено ' + done + ' из ' + Q.length +
        '. «Не знаю» — тоже ответ: покупатель его не примет, но здесь он честнее пропуска.</p>';
      out.className = 'dg__out';
      return;
    }
    /* «не знаю» приравнивается к «нет»: на переговорах это одно и то же */
    var maxW = Q.reduce(function (a, q) { return a + q.w; }, 0);
    var gotW = Q.reduce(function (a, q, i) { return a + (answers[i] === 'yes' ? q.w : 0); }, 0);
    var pct = Math.round(gotW / maxW * 100);
    var gaps = Q.filter(function (q, i) { return answers[i] !== 'yes'; });
    var hot = gaps.filter(function (q) { return q.w === 3; }).length;

    var verdict =
      pct >= 85 ? 'Объект готов к разговору. Останется собрать материалы в один документ.' :
      pct >= 60 ? 'База есть, но пробелы попадают в переговоры. Их закрывают за две–три недели.' :
      pct >= 35 ? 'Половина того, что спросит покупатель, пока без ответа. Выходить на рынок рано.' :
                  'Объект к продаже не готов: почти всё придётся выяснять при покупателе, а это торг.';

    var html =
      '<div class="dg__score">' +
        '<div class="dg__pct"><b>' + pct + '&thinsp;%</b><span>готовность к продаже</span></div>' +
        '<div class="dg__track"><i style="width:' + pct + '%"></i></div>' +
        '<p class="dg__verdict">' + verdict + '</p>' +
        (hot ? '<p class="dg__hot">Из них <b>' + hot + '</b> — то, без чего сделка не двигается вовсе.</p>' : '') +
      '</div>';

    if (gaps.length) {
      html += '<div class="dg__gaps"><h3>Что закрыть и за какой срок</h3>';
      gaps.sort(function (a, b) { return b.w - a.w; }).forEach(function (q) {
        html += '<div class="dg__g' + (q.w === 3 ? ' is-hot' : '') + '">' +
          '<b>' + q.t + '</b>' +
          '<p>' + q.why + '</p>' +
          '<span class="dg__fix">' + q.fix + '</span>' +
          '</div>';
      });
      html += '</div>';
    }

    html +=
      '<div class="dg__cta">' +
        '<p>Сроки выше — по нашим работам, при условии что документы у собственника есть ' +
        'и он отвечает на вопросы. Разберём вашу ситуацию за двадцать минут и скажем, ' +
        'что реально закрыть, а что не решается вовсе.</p>' +
        '<a class="btn" href="index.html#contact"><span>Обсудить объект</span></a>' +
        '<button class="btn btn--ghost" type="button" id="dg-reset"><span>Пройти заново</span></button>' +
      '</div>';

    out.className = 'dg__out is-on';
    out.innerHTML = html;
    var r = document.getElementById('dg-reset');
    if (r) r.addEventListener('click', function () { answers = {}; render(); root.scrollIntoView({ behavior: 'smooth' }); });
  }

  render();
})();
